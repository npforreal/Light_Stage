#!/usr/bin/env python3
"""
Usage: python3 scripts/gen_tokens.py

Generates src/styles/tokens.css from perceptual OKLCH color specifications.
Adheres to docs/COLOR_COURSE.md:
- surface-0..3 (dark elevated tiers)
- text-1..3 (high contrast text)
- border-subtle/default/strong
- dept-lx/vx/sq/st (same L, same C, 90° hue separation)
- status-go/standby/hold/danger
"""

import math
import os
import sys

def oklch_to_linear_srgb(l, c, h_deg):
    h_rad = math.radians(h_deg)
    a = c * math.cos(h_rad)
    b = c * math.sin(h_rad)

    # Oklab to LMS
    l_ = l + 0.3963377774 * a + 0.2158037573 * b
    m_ = l - 0.1055613458 * a - 0.0638541728 * b
    s_ = l - 0.0894841775 * a - 1.2914855480 * b

    l_cubed = l_ * l_ * l_
    m_cubed = m_ * m_ * m_
    s_cubed = s_ * s_ * s_

    # LMS to Linear sRGB
    r = +4.0767416621 * l_cubed - 3.3077115913 * m_cubed + 0.2309699292 * s_cubed
    g = -1.2684380046 * l_cubed + 2.6097574011 * m_cubed - 0.3413193965 * s_cubed
    b_out = -0.0041960863 * l_cubed - 0.7034186147 * m_cubed + 1.7076147010 * s_cubed

    return r, g, b_out

def linear_to_srgb_hex(r, g, b):
    def channel(val):
        clamped = max(0.0, min(1.0, val))
        if clamped <= 0.0031308:
            srgb = clamped * 12.92
        else:
            srgb = 1.055 * (clamped ** (1.0 / 2.4)) - 0.055
        return int(round(max(0, min(255, srgb * 255))))

    ir = channel(r)
    ig = channel(g)
    ib = channel(b)
    return f"#{ir:02x}{ig:02x}{ib:02x}"

def oklch_to_hex(l, c, h):
    r, g, b = oklch_to_linear_srgb(l, c, h)
    return linear_to_srgb_hex(r, g, b)

TOKENS = [
    # Surface Elevation (L 0.14 -> 0.28, subtle cool dark)
    ("surface-0", 0.14, 0.015, 260, "Canvas base surface"),
    ("surface-1", 0.18, 0.018, 260, "Panels, headers, sidebar"),
    ("surface-2", 0.23, 0.020, 260, "Cards, table headers"),
    ("surface-3", 0.28, 0.022, 260, "Hover states, popovers"),

    # Borders
    ("border-subtle", 0.26, 0.015, 260, "Subtle dividers"),
    ("border-default", 0.34, 0.018, 260, "Standard card & table borders"),
    ("border-strong", 0.42, 0.022, 260, "Highlighted / active borders"),

    # Text
    ("text-1", 0.95, 0.010, 260, "Primary headline / active cue text"),
    ("text-2", 0.78, 0.015, 260, "Secondary content text"),
    ("text-3", 0.60, 0.018, 260, "Muted labels & timestamps"),

    # Brand Accent
    ("accent", 0.75, 0.120, 230, "Active tab / focus ring"),

    # Stage Departments (Equal L 0.72, equal C 0.09, 90 deg hue separation)
    ("dept-lx", 0.72, 0.090, 75, "Lighting department indicator"),
    ("dept-vx", 0.72, 0.090, 300, "Visual LED department indicator"),
    ("dept-sq", 0.72, 0.090, 195, "Sound department indicator"),
    ("dept-st", 0.72, 0.090, 125, "Stage action department indicator"),

    # Operating Statuses (Distinct high-clarity cues)
    ("status-go", 0.75, 0.160, 145, "Active Go status (emerald)"),
    ("status-standby", 0.78, 0.150, 80, "Standby status (amber-orange)"),
    ("status-hold", 0.72, 0.120, 245, "Hold status (steel blue)"),
    ("status-danger", 0.65, 0.200, 25, "Overrun & alert status (vivid red)"),
]

def main():
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    target_path = os.path.join(repo_root, "src", "styles", "tokens.css")

    lines = [
        "/* Generated by scripts/gen_tokens.py - DO NOT EDIT MANUALLY */",
        "/* Adheres to OKLCH perceptual color tokens (docs/COLOR_COURSE.md) */",
        "",
        ":root {",
    ]

    for name, l, c, h, desc in TOKENS:
        hex_code = oklch_to_hex(l, c, h)
        lines.append(f"  /* {desc} (OKLCH {l:.2f} {c:.3f} {h}deg) */")
        lines.append(f"  --color-{name}: {hex_code};")

    lines.append("}")
    lines.append("")

    output = "\n".join(lines)
    os.makedirs(os.path.dirname(target_path), exist_ok=True)
    with open(target_path, "w", encoding="utf-8") as f:
        f.write(output)

    print(f"Generated {len(TOKENS)} semantic color tokens -> {target_path}")

if __name__ == "__main__":
    main()
